public class operators {
    public static void main(String[] args){

        // operators
        // arithmetic
        int a = 1 ;
        int b = 2;
        int sum = a + b;
        int diff = a - b;
        int mul = a * b;
        int div = a/b;
        // module
        int modulo = a%b;
        System.out.println(sum);
        System.out.println(diff);
        System.out.println(mul);
        System.out.println(div);
        System.out.println(modulo);

        // Assingment operator
        /*

         */
        int numb =1 ;
        // numb = numb + 1;
        numb++;
        System.out.println(numb++);
        System.out.println(++numb);

        /*
        numb--
        --numb
        
        */

    }
}
